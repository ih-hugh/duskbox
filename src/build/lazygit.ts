import { buildPalette, type VariantConfig } from "../palette/types";

// Lazygit theme emitter. Lazygit colors live under `gui.theme`, each value an array
// (hex color plus optional attributes like `bold`). Generated from the same OKLCH
// palette as the Neovim/VS Code emitters so the git TUI never drifts from the editor.
// Reference: https://github.com/jesseduffield/lazygit/blob/master/docs/Config.md#color-attributes

/** Render one `gui.theme` entry: a hex color and optional trailing attributes. */
function entry(indent: string, key: string, hex: string, ...attrs: string[]): string {
  const items = [hex, ...attrs].map((v) => `${indent}  - "${v}"`).join("\n");
  return `${indent}${key}:\n${items}`;
}

/** A standalone lazygit theme config (the `gui.theme` block) for one variant. */
export function buildLazygit(v: VariantConfig): string {
  const p = buildPalette(v);
  const a = p.accents;
  const t = "    "; // entries sit under gui: > theme:
  const theme = [
    entry(t, "activeBorderColor", a.blue, "bold"),
    entry(t, "inactiveBorderColor", p.fg2),
    entry(t, "searchingActiveBorderColor", a.yellow, "bold"),
    entry(t, "optionsTextColor", a.blue),
    entry(t, "selectedLineBgColor", p.bg2),
    entry(t, "cherryPickedCommitBgColor", p.bg3),
    entry(t, "cherryPickedCommitFgColor", a.magenta),
    entry(t, "markedBaseCommitBgColor", p.bg3),
    entry(t, "markedBaseCommitFgColor", a.yellow),
    entry(t, "unstagedChangesColor", a.red),
    entry(t, "defaultFgColor", p.fg0),
  ].join("\n");

  return [
    `# duskbox-${v.name} — lazygit theme (generated by duskbox)`,
    `# Merge this gui.theme block into your lazygit config.yml`,
    `# (macOS: ~/Library/Application Support/lazygit/config.yml, else ~/.config/lazygit/config.yml).`,
    `gui:`,
    `  theme:`,
    theme,
    `  authorColors:`,
    `    "*": "${a.purple}"`,
    ``,
  ].join("\n");
}
