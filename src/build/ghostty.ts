import { buildPalette, type VariantConfig } from "../palette/types";

// Ghostty-compatible terminal theme emitter. cmux uses libghostty and reads the
// same theme files, so these files work in both Ghostty and cmux.
// Reference: https://cmux.com/docs/configuration and /configuration/themes

/** A standalone Ghostty/cmux theme file for one variant. */
export function buildGhostty(v: VariantConfig): string {
  const p = buildPalette(v);
  const a = p.accents;
  const ui = p.signature ?? a.blue; // signature variants carry chrome into the terminal cursor too
  const lines = [
    `# duskbox-${v.name} — Ghostty/cmux theme (generated by duskbox)`,
    `# Install in ~/.config/ghostty/themes/ and reference as: theme = duskbox-${v.name}`,
    ``,
    `background = ${p.bg0}`,
    `foreground = ${p.fg0}`,
    `cursor-color = ${ui}`,
    `cursor-text = ${p.bg0}`,
    `selection-background = ${p.bg3}`,
    `selection-foreground = ${p.fg0}`,
    `split-divider-color = ${p.bg3}`,
    ``,
    `palette = 0=${p.bg2}`,
    `palette = 1=${a.red}`,
    `palette = 2=${a.green}`,
    `palette = 3=${a.yellow}`,
    `palette = 4=${a.blue}`,
    `palette = 5=${a.magenta}`,
    `palette = 6=${a.cyan}`,
    `palette = 7=${p.fg1}`,
    `palette = 8=${p.bg3}`,
    `palette = 9=${a.red}`,
    `palette = 10=${a.green}`,
    `palette = 11=${a.yellow}`,
    `palette = 12=${a.blue}`,
    `palette = 13=${a.magenta}`,
    `palette = 14=${a.cyan}`,
    `palette = 15=${p.fg0}`,
    ``,
  ];
  return lines.join("\n");
}
