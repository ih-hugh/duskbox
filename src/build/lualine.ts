import { buildPalette, type VariantConfig } from "../palette/types";

// A lualine theme table. Mode segment `a` follows the variant (normal = signature); b/c neutral.
export function buildLualine(v: VariantConfig): string {
  const p = buildPalette(v);
  const a = p.accents;
  const ui = p.signature ?? a.blue;
  const mode = (bg: string) =>
    `{ a = { fg = "${p.bg0}", bg = "${bg}", gui = "bold" }, b = { fg = "${p.fg1}", bg = "${p.bg2}" }, c = { fg = "${p.fg2}", bg = "${p.bg1}" } }`;
  const inactive = `{ a = { fg = "${p.fg2}", bg = "${p.bg1}" }, b = { fg = "${p.fg2}", bg = "${p.bg1}" }, c = { fg = "${p.fg2}", bg = "${p.bg1}" } }`;
  return `-- generated by duskbox; do not edit by hand
return {
  normal = ${mode(ui)},
  insert = ${mode(a.green)},
  visual = ${mode(a.purple)},
  replace = ${mode(a.red)},
  command = ${mode(a.yellow)},
  inactive = ${inactive},
}
`;
}
